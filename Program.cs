//콘솔 출력
Console.WriteLine("Hello world!");
//여러 항목 인쇄
Console.WriteLine("Hello{0}", " world!");
//이스케이프 문자(줄바꿈)
Console.WriteLine("Hello\nworld!");
//이스케이프 문자(탭 공간 추가)
Console.WriteLine("Hi what's your name?: \t");
Console.WriteLine("How old are you?: \t");
//이스케이프 문자(백슬래시 출력)
Console.WriteLine("cd c\\users\\Desktop");
//이스케이프 문자(큰따옴표 출력)
Console.WriteLine("She said, \"HI!\"");
//Console.WriteLine과 Console.Write의 차이(줄바꿈 유무)
Console.Write("Hello");
Console.Write(" ");
Console.Write("world!");
Console.WriteLine("Hello");
Console.WriteLine(" ");
Console.WriteLine("world!");

